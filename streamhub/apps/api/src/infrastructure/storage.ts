import {
  AbortMultipartUploadCommand,
  CompleteMultipartUploadCommand,
  CreateMultipartUploadCommand,
  DeleteObjectCommand,
  GetObjectCommand,
  HeadBucketCommand,
  HeadObjectCommand,
  S3Client,
  S3ServiceException,
  UploadPartCommand,
} from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import type { AppConfig } from '../config/env.ts';

/**
 * The only place that talks to object storage (ADR-044). Everything else uses
 * this interface, so the same code runs against MinIO-compatible storage
 * locally and S3 on AWS, and tests can swap in a fake if they need to.
 *
 * One instance per bucket. Keys are always generated by the API, never taken
 * from user input.
 */
export interface ObjectStorage {
  readonly bucket: string;
  createMultipartUpload(key: string, contentType: string): Promise<string>;
  presignUploadPart(
    key: string,
    uploadId: string,
    partNumber: number,
    expiresInSeconds: number,
  ): Promise<string>;
  completeMultipartUpload(
    key: string,
    uploadId: string,
    parts: { partNumber: number; etag: string }[],
  ): Promise<void>;
  /** Idempotent: aborting an upload that no longer exists is not an error. */
  abortMultipartUpload(key: string, uploadId: string): Promise<void>;
  /** Size and type of an object, or null if it does not exist. */
  head(key: string): Promise<{ sizeBytes: number; contentType: string | undefined } | null>;
  /** Bytes [start, endInclusive] of an object (for file signature checks). */
  readRange(key: string, start: number, endInclusive: number): Promise<Uint8Array>;
  /** Idempotent. */
  delete(key: string): Promise<void>;
  /**
   * A time-limited GET URL. Storage itself serves byte ranges (206), so the
   * API never streams video. With role credentials the URL also stops working
   * when those temporary credentials expire (a few hours on EC2).
   */
  presignGet(key: string, expiresInSeconds: number): Promise<string>;
  /** Throws if the bucket is unreachable or access is denied. */
  ping(): Promise<void>;
}

/** Thrown when storage rejects the parts on complete (wrong ETag, missing part, too small). */
export class StorageRejectedError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'StorageRejectedError';
  }
}

type StorageConfig = Pick<
  AppConfig,
  'S3_ENDPOINT' | 'S3_REGION' | 'S3_FORCE_PATH_STYLE' | 'S3_ACCESS_KEY_ID' | 'S3_SECRET_ACCESS_KEY'
>;

export function createS3Client(config: StorageConfig): S3Client {
  return new S3Client({
    region: config.S3_REGION,
    ...(config.S3_ENDPOINT ? { endpoint: config.S3_ENDPOINT } : {}),
    forcePathStyle: config.S3_FORCE_PATH_STYLE,
    // Static keys only locally. Without them the SDK's default chain is used:
    // on EC2 the instance role, on ECS the task role. Nothing to store or rotate.
    ...(config.S3_ACCESS_KEY_ID && config.S3_SECRET_ACCESS_KEY
      ? {
          credentials: {
            accessKeyId: config.S3_ACCESS_KEY_ID,
            secretAccessKey: config.S3_SECRET_ACCESS_KEY,
          },
        }
      : {}),
    // Newer SDKs add CRC checksums to every request by default, which also ends
    // up in pre-signed URLs and breaks plain browser PUTs and S3-compatible
    // servers. Only send them where the S3 API requires them.
    requestChecksumCalculation: 'WHEN_REQUIRED',
    responseChecksumValidation: 'WHEN_REQUIRED',
    maxAttempts: 3,
  });
}

function isNotFound(err: unknown): boolean {
  if (!(err instanceof S3ServiceException)) return false;
  return (
    err.$metadata.httpStatusCode === 404 ||
    err.name === 'NotFound' ||
    err.name === 'NoSuchKey' ||
    err.name === 'NoSuchUpload'
  );
}

export class S3ObjectStorage implements ObjectStorage {
  readonly bucket: string;
  private readonly client: S3Client;

  constructor(client: S3Client, bucket: string) {
    this.client = client;
    this.bucket = bucket;
  }

  async createMultipartUpload(key: string, contentType: string): Promise<string> {
    const result = await this.client.send(
      new CreateMultipartUploadCommand({ Bucket: this.bucket, Key: key, ContentType: contentType }),
    );
    if (!result.UploadId) throw new Error('storage returned no UploadId');
    return result.UploadId;
  }

  presignUploadPart(
    key: string,
    uploadId: string,
    partNumber: number,
    expiresInSeconds: number,
  ): Promise<string> {
    return getSignedUrl(
      this.client,
      new UploadPartCommand({
        Bucket: this.bucket,
        Key: key,
        UploadId: uploadId,
        PartNumber: partNumber,
      }),
      { expiresIn: expiresInSeconds },
    );
  }

  async completeMultipartUpload(
    key: string,
    uploadId: string,
    parts: { partNumber: number; etag: string }[],
  ): Promise<void> {
    try {
      await this.client.send(
        new CompleteMultipartUploadCommand({
          Bucket: this.bucket,
          Key: key,
          UploadId: uploadId,
          MultipartUpload: {
            Parts: parts.map((part) => ({ PartNumber: part.partNumber, ETag: part.etag })),
          },
        }),
      );
    } catch (err) {
      // 400-class answers mean the client's parts are wrong, not that storage is down.
      const status = err instanceof S3ServiceException ? err.$metadata.httpStatusCode : undefined;
      if (status !== undefined && status >= 400 && status < 500) {
        throw new StorageRejectedError(err instanceof Error ? err.name : 'rejected');
      }
      throw err;
    }
  }

  async abortMultipartUpload(key: string, uploadId: string): Promise<void> {
    try {
      await this.client.send(
        new AbortMultipartUploadCommand({ Bucket: this.bucket, Key: key, UploadId: uploadId }),
      );
    } catch (err) {
      if (!isNotFound(err)) throw err;
    }
  }

  async head(key: string) {
    try {
      const result = await this.client.send(
        new HeadObjectCommand({ Bucket: this.bucket, Key: key }),
      );
      return { sizeBytes: result.ContentLength ?? 0, contentType: result.ContentType };
    } catch (err) {
      if (isNotFound(err)) return null;
      throw err;
    }
  }

  async readRange(key: string, start: number, endInclusive: number): Promise<Uint8Array> {
    const result = await this.client.send(
      new GetObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Range: `bytes=${start}-${endInclusive}`,
      }),
    );
    if (!result.Body) return new Uint8Array();
    return result.Body.transformToByteArray();
  }

  async delete(key: string): Promise<void> {
    try {
      await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
    } catch (err) {
      if (!isNotFound(err)) throw err;
    }
  }

  presignGet(key: string, expiresInSeconds: number): Promise<string> {
    return getSignedUrl(
      this.client,
      new GetObjectCommand({
        Bucket: this.bucket,
        Key: key,
        ResponseContentDisposition: 'inline',
        // Private, per-user URLs: browsers may cache, shared caches must not.
        ResponseCacheControl: 'private, max-age=3600',
      }),
      { expiresIn: expiresInSeconds },
    );
  }

  async ping(): Promise<void> {
    await this.client.send(new HeadBucketCommand({ Bucket: this.bucket }));
  }
}
